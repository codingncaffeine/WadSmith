// Regenerates data/udmf/actions.json (action special names, numbers and line argument counts)
// from GZDoom's own list for a given engine tag.
//   node tools/gen-actions.mjs g4.14.2
import { writeFileSync } from 'node:fs';

const tag = process.argv[2];
if (!tag) {
    console.error('usage: node tools/gen-actions.mjs ENGINE_TAG   (e.g. g4.14.2)');
    process.exit(2);
}

const url = `https://raw.githubusercontent.com/ZDoom/gzdoom/${tag}/src/playsim/actionspecials.h`;
const res = await fetch(url);
if (!res.ok) {
    console.error(`could not fetch ${url}: ${res.status}`);
    process.exit(1);
}

const text = await res.text();
const actions = [];
for (const m of text.matchAll(/^\s*DEFINE_SPECIAL\(\s*(\w+)\s*,\s*(\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(\d+)\s*\)/gm)) {
    actions.push({ number: +m[2], name: m[1], lineArgs: +m[5] });
}

if (actions.length < 200) {
    console.error(`only ${actions.length} actions found; the source format has changed`);
    process.exit(1);
}

actions.sort((a, b) => a.number - b.number);
const out = {
    comment: `Action special numbers, names and how many arguments a line or thing gives them, as GZDoom ${tag} defines them. Generated by tools/gen-actions.mjs; friendly names and descriptions live elsewhere.`,
    engine: tag,
    actions,
};
writeFileSync(new URL('../data/udmf/actions.json', import.meta.url), JSON.stringify(out, null, 2) + '\n');
console.log(`${actions.length} actions written`);
